<?php
declare(strict_types=1);
use Illuminate\Support\Facades\Route;
use PortMap\LibreNMS\Http\PortMapController;
use PortMap\LibreNMS\Http\PublishedMapController;
use PortMap\LibreNMS\Http\PhysicalMapController;
use PortMap\LibreNMS\Http\InfrastructureController;
use PortMap\LibreNMS\Http\MorMapWidgetController;
// LibreNMS discovers dashboard widgets by this exact, unnested prefix.
Route::prefix('ajax/dash')->middleware(['web', 'auth'])->group(function () {
    Route::post('mormap', MorMapWidgetController::class)->name('mormap.widget');
});
Route::middleware(['web', 'auth'])->group(function () {
    Route::get('/plugin/portmap', [PortMapController::class, 'home'])->name('portmap.home');
    Route::prefix('/plugin/mormap')->middleware(\PortMap\LibreNMS\Http\WorkspaceMiddleware::class)->name('mormap.')->group(function () {
        Route::get('/', [PortMapController::class, 'home'])->name('home');
        Route::get('/assets/{file}', [PortMapController::class, 'asset'])->name('asset');
        Route::post('/undo',[InfrastructureController::class,'undo']);
        Route::get('/infrastructure',[InfrastructureController::class,'index'])->name('infrastructure');
        Route::post('/infrastructure/components',[InfrastructureController::class,'add']);
        Route::post('/infrastructure/groups',[InfrastructureController::class,'groups']);
        Route::post('/infrastructure/connections',[InfrastructureController::class,'connection']);
        Route::put('/infrastructure/connections/{id}',[InfrastructureController::class,'connection'])->whereUuid('id');
        Route::delete('/infrastructure/connections/{id}',[InfrastructureController::class,'connection'])->whereUuid('id');
        Route::post('/infrastructure/ports',[InfrastructureController::class,'addPort']);
        Route::get('/ports/{port}/details',[InfrastructureController::class,'port'])->whereNumber('port')->name('port.details');
        Route::get('/published', [PortMapController::class, 'publishedMaps'])->name('published');
        Route::get('/asset-library', [PortMapController::class, 'libraryHome'])->name('library.home');
        Route::get('/library', [PortMapController::class, 'library'])->name('library');
        Route::get('/library/{id}', [PortMapController::class, 'libraryAsset'])->where('id', '[A-Za-z0-9_-]+');
        Route::get('/library/{id}/usage', [PortMapController::class, 'assetUsage'])->where('id', '[A-Za-z0-9_-]+');
        Route::delete('/library/{id}', [PortMapController::class, 'deleteAsset'])->where('id', '[A-Za-z0-9_-]+');
        Route::post('/library/{id}/replace', [PortMapController::class, 'replaceAsset'])->where('id', '[A-Za-z0-9_-]+');
        Route::put('/library/{id}', [PortMapController::class, 'updateAsset'])->where('id', '[A-Za-z0-9_-]+');
        Route::get('/library/{id}/export', [PortMapController::class, 'exportAsset'])->where('id', '[A-Za-z0-9_-]+');
        Route::prefix('/physical')->name('physical.')->group(function () {
            Route::get('/', [PhysicalMapController::class, 'home'])->name('home');
            Route::get('/maps', [PhysicalMapController::class, 'maps']);
            Route::post('/maps', [PhysicalMapController::class, 'create']);
            Route::get('/maps/{id}', [PhysicalMapController::class, 'load'])->whereUuid('id');
            Route::put('/maps/{id}', [PhysicalMapController::class, 'save'])->whereUuid('id');
            Route::patch('/maps/{id}/name', [PhysicalMapController::class, 'rename'])->whereUuid('id');
            Route::delete('/maps/{id}', [PhysicalMapController::class, 'delete'])->whereUuid('id');
            Route::post('/maps/{id}/publish', [PhysicalMapController::class, 'publish'])->whereUuid('id');
            Route::delete('/maps/{id}/publish', [PhysicalMapController::class, 'unpublish'])->whereUuid('id')->name('unpublish');
            Route::post('/maps/{id}/status', [PhysicalMapController::class, 'status'])->whereUuid('id');
            Route::get('/view/{id}', [PhysicalMapController::class, 'view'])->whereUuid('id')->name('viewer');
            Route::get('/view/{id}/data', [PhysicalMapController::class, 'viewData'])->whereUuid('id');
            Route::post('/view/{id}/status', [PhysicalMapController::class, 'viewStatus'])->whereUuid('id');
            Route::get('/view/{id}/images/{image}', [PhysicalMapController::class, 'viewImage'])->whereUuid('id')->where('image', '[A-Za-z0-9_-]+');
        });
        Route::post('/maps/{id}/publish', [PortMapController::class, 'publish'])->whereUuid('id');
        Route::get('/view', [PublishedMapController::class, 'index'])->name('viewer.index');
        Route::get('/view/{id}', [PublishedMapController::class, 'home'])->whereUuid('id')->name('viewer');
        Route::get('/view/{id}/data', [PublishedMapController::class, 'load'])->whereUuid('id');
        Route::post('/view/{id}/status', [PublishedMapController::class, 'status'])->whereUuid('id');
        Route::get('/view/{id}/images/{image}', [PublishedMapController::class, 'image'])->whereUuid('id')->where('image', '[A-Za-z0-9_-]+');
        Route::get('/devices', [PortMapController::class, 'devices'])->name('devices');
        Route::get('/devices/{device}/ports', [PortMapController::class, 'ports'])->whereNumber('device');
        Route::post('/status', [PortMapController::class, 'status']);
        Route::get('/maps', [PortMapController::class, 'maps']);
        Route::post('/maps', [PortMapController::class, 'create']);
        Route::get('/maps/{id}', [PortMapController::class, 'load'])->whereUuid('id');
        Route::put('/maps/{id}', [PortMapController::class, 'save'])->whereUuid('id');
        Route::patch('/maps/{id}/name', [PortMapController::class, 'rename'])->whereUuid('id');
        Route::delete('/maps/{id}', [PortMapController::class, 'delete'])->whereUuid('id');
        Route::post('/images', [PortMapController::class, 'upload']);
        Route::get('/images/{id}', [PortMapController::class, 'image'])->where('id', '[A-Za-z0-9_-]+')->name('image');
    });
});
